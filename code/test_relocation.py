"""Run the entire package in a fresh temporary folder, without prior outputs.

Immutable data are hard-linked when possible (read-only use, no duplication of
1.8 GiB); executable files and manifests are copied. This is a portability test,
not an independent estimator: the independent evidence remains reference/.
"""
from pathlib import Path
import json
import os
import shutil
import subprocess
import sys
import tempfile
from package_io import ROOT,logs,write,sha,require


def main():
    target=Path(tempfile.mkdtemp(prefix='ns_paul_relocation_'))
    immutable={'data','reference'}
    for name in ['code','config','data','reference','provenance','docs']:
        for source in (ROOT/name).rglob('*'):
            if not source.is_file() or '__pycache__' in source.parts:
                continue
            dest=target/source.relative_to(ROOT)
            dest.parent.mkdir(parents=True,exist_ok=True)
            if name in immutable:
                try:
                    os.link(source,dest)
                    continue
                except OSError:
                    pass
            shutil.copy2(source,dest)
    for name in ['replicate.py','requirements.txt','README.md']:
        shutil.copy2(ROOT/name,target/name)
    print('Fresh relocated folder:',target,flush=True)
    print('No output directory or previous test results were copied.',flush=True)
    command=[sys.executable,'-B',str(target/'replicate.py')]
    log=logs()/'relocation_stdout.log'
    with log.open('w') as stream:
        run=subprocess.run(command+['all'],cwd=target,stdout=stream,stderr=subprocess.STDOUT)
    require(run.returncode==0,'Relocated all-stage run failed; inspect '+str(log))
    cert=json.loads((target/'output/replication_check.json').read_text())
    require(cert['status']=='PASS','Relocated numerical checks failed')
    # Fail-closed check: change only a COPIED temporary manifest, never data.
    manifest=target/'provenance/input_manifest.json'
    before=manifest.read_bytes()
    try:
        changed=json.loads(before)
        changed[0]['sha256']='0'*64
        manifest.write_text(json.dumps(changed),encoding='utf-8')
        rejection=subprocess.run(command+['verify'],cwd=target,stdout=subprocess.PIPE,
                                 stderr=subprocess.STDOUT,text=True)
        require(rejection.returncode!=0 and 'Input changed:' in rejection.stdout,
                'Changed-input guard did not reject the altered manifest')
    finally:
        manifest.write_bytes(before)
    final=subprocess.run(command+['verify'],cwd=target,stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT,text=True)
    require(final.returncode==0,'Verification failed after restoring temporary manifest')
    write(ROOT/'output/relocation_check.json',dict(
        status='PASS',directory=str(target),copied_existing_outputs=False,
        full_stage_run=True,changed_input_rejected=True,
        references='Frozen independently saved outputs, not regenerated by this test',
        package_pdf_sha256=sha(target/'output/pdf/NS_results_recap.pdf'),
        log=str(log),temporary_directory_retained=True))
    print('RELOCATION PASS: full rebuild/re-estimation/render; changed-input guard rejected tampering.',flush=True)


if __name__=='__main__':
    main()
